import { stripOuterMathDelimiters } from './latex';

export interface StandaloneOfflineHtmlOptions {
  latex: string;
  isZh: boolean;
  svgHtml?: string;
  katexHtml?: string;
}

/**
 * 严格清洗文件名：
 * 1. 过滤任何路径跳转字符 (..)、路径分隔符 (/ \)、控制字符 (0x00-0x1F, 0x7F)
 * 2. 过滤危险 HTML 字符 (< > : " ' | ? *)
 * 3. 截断合理长度，默认回退 'formula'
 */
export function sanitizeFilename(input: string): string {
  if (!input || typeof input !== 'string') return 'formula';

  // 移除非法路径与特殊符号，仅保留中英文字符、数字、下划线与短横线
  let sanitized = input
    .normalize('NFKC')
    .replace(/[\u0000-\u001F\u007F-\u009F]/g, '') // 控制字符
    .replace(/[\\/:*?"<>|`$#@!%^&+=~[\]{}();,\s]+/g, '_') // 路径与特殊标点
    .replace(/\.+/g, '_') // 防止连续点或路径跳转
    .replace(/^_+|_+$/g, '') // 去除首尾下划线
    .slice(0, 32); // 限制文件名长度

  return sanitized || 'formula';
}

/**
 * HTML 内容转义，防止 XSS 与标签闭合
 */
export function escapeHtml(str: string): string {
  if (!str) return '';
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * JSON 字符串在 <script> 上下文中的安全转义
 * 彻底杜绝 </script>、<!--、<script>、U+2028 (LINE SEPARATOR)、U+2029 (PARAGRAPH SEPARATOR) 引起的逃逸与执行
 */
export function escapeJsonForScript(jsonStr: string): string {
  return jsonStr
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}

/**
 * 生成 100% 独立离线单文件 HTML
 * - 0 外部网络请求（无 jsDelivr、无 CDN、无外部 WebFont 字体加载）
 * - 静态嵌入矢量 SVG 或预渲染 HTML，断网立即可用
 * - 通过 <script id="formula-data" type="application/json"> 安全存储原始数据
 * - 响应式排版与长公式水平横向滚动
 * - 内置安全的点击一键复制源码交互
 */
export function generateStandaloneOfflineHtml({
  latex,
  isZh,
  svgHtml,
  katexHtml,
}: StandaloneOfflineHtmlOptions): string {
  const { cleaned } = stripOuterMathDelimiters(latex);
  const safeFilenameTitle = sanitizeFilename(cleaned);
  const safeJsonData = escapeJsonForScript(JSON.stringify(cleaned));
  const escapedCode = escapeHtml(cleaned);

  // 决定公式静态显示内容（首选 MathJax 纯路径矢量 SVG，其次 KaTeX 预渲染 HTML，兜底代码块）
  let displayContent = '';
  if (svgHtml && svgHtml.trim()) {
    displayContent = `<div class="svg-container">${svgHtml}</div>`;
  } else if (katexHtml && katexHtml.trim()) {
    displayContent = `<div class="katex-container">${katexHtml}</div>`;
  } else {
    displayContent = `<div class="fallback-code-container"><pre><code>${escapedCode}</code></pre></div>`;
  }

  const langAttr = isZh ? 'zh-CN' : 'en';
  const pageTitle = isZh ? `Visual-TeX 导出公式 - ${safeFilenameTitle}` : `Visual-TeX Formula - ${safeFilenameTitle}`;
  const badgeText = isZh ? '纯前端 100% 离线单文件' : '100% Standalone Offline File';
  const headerTitle = isZh ? 'LaTeX 公式离线存档' : 'LaTeX Formula Offline Archive';
  const formulaLabel = isZh ? '公式高清渲染' : 'Rendered Formula';
  const sourceLabel = isZh ? 'LaTeX 源码' : 'LaTeX Source';
  const copyBtnLabel = isZh ? '复制 LaTeX 源码' : 'Copy LaTeX Source';
  const copiedToastLabel = isZh ? '已成功复制到剪贴板！' : 'Copied to clipboard!';
  const footerText = isZh
    ? '由 Visual-TeX 纯前端公式工坊生成 · 无需任何外部网络连接'
    : 'Generated by Visual-TeX Studio · No external network dependencies';

  return `<!DOCTYPE html>
<html lang="${langAttr}">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${escapeHtml(pageTitle)}</title>
  <style>
    :root {
      --bg-body: #0b0f19;
      --bg-card: #151d2e;
      --bg-card-inner: #0d1320;
      --border-color: #2a374d;
      --text-main: #f1f5f9;
      --text-muted: #94a3b8;
      --primary: #38bdf8;
      --primary-hover: #0284c7;
      --success: #10b981;
    }
    *, *::before, *::after {
      box-sizing: border-box;
      margin: 0;
      padding: 0;
    }
    body {
      background-color: var(--bg-body);
      color: var(--text-main);
      font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif;
      min-height: 100vh;
      display: flex;
      flex-direction: column;
      align-items: center;
      justify-content: center;
      padding: 24px 16px;
      line-height: 1.5;
    }
    .wrapper {
      max-width: 900px;
      width: 100%;
      background: var(--bg-card);
      border: 1px solid var(--border-color);
      border-radius: 16px;
      padding: 32px 24px;
      box-shadow: 0 16px 40px rgba(0, 0, 0, 0.45);
    }
    .header-area {
      text-align: center;
      margin-bottom: 24px;
    }
    .badge {
      display: inline-block;
      font-size: 11px;
      font-weight: 600;
      letter-spacing: 0.05em;
      text-transform: uppercase;
      color: var(--primary);
      background: rgba(56, 189, 248, 0.12);
      border: 1px solid rgba(56, 189, 248, 0.28);
      border-radius: 9999px;
      padding: 3px 12px;
      margin-bottom: 10px;
    }
    h1 {
      font-size: 1.45rem;
      font-weight: 700;
      color: #ffffff;
      letter-spacing: -0.01em;
    }
    .section-title {
      font-size: 0.8rem;
      font-weight: 600;
      text-transform: uppercase;
      letter-spacing: 0.06em;
      color: var(--text-muted);
      margin-bottom: 8px;
    }
    .formula-stage {
      background: var(--bg-card-inner);
      border: 1px solid var(--border-color);
      border-radius: 12px;
      padding: 28px 16px;
      margin-bottom: 24px;
      display: flex;
      align-items: center;
      justify-content: center;
      overflow-x: auto;
      -webkit-overflow-scrolling: touch;
    }
    .svg-container {
      display: inline-flex;
      align-items: center;
      justify-content: center;
      max-width: 100%;
    }
    .svg-container svg {
      max-width: 100%;
      height: auto;
      display: block;
    }
    .source-block {
      background: var(--bg-card-inner);
      border: 1px solid var(--border-color);
      border-radius: 12px;
      padding: 16px;
      position: relative;
    }
    .source-header {
      display: flex;
      align-items: center;
      justify-content: space-between;
      margin-bottom: 10px;
    }
    .copy-btn {
      display: inline-flex;
      align-items: center;
      gap: 6px;
      background: #1e293b;
      color: #e2e8f0;
      border: 1px solid #475569;
      border-radius: 6px;
      padding: 6px 12px;
      font-size: 12px;
      font-weight: 500;
      cursor: pointer;
      transition: all 0.15s ease;
      user-select: none;
    }
    .copy-btn:hover {
      background: #334155;
      border-color: #64748b;
      color: #ffffff;
    }
    .copy-btn.copied {
      background: rgba(16, 185, 129, 0.2);
      border-color: var(--success);
      color: var(--success);
    }
    pre {
      font-family: ui-monospace, SFMono-Regular, Menlo, Monaco, Consolas, monospace;
      font-size: 13px;
      color: #93c5fd;
      overflow-x: auto;
      white-space: pre-wrap;
      word-break: break-all;
      margin: 0;
      line-height: 1.6;
    }
    .footer-note {
      text-align: center;
      margin-top: 24px;
      font-size: 12px;
      color: var(--text-muted);
    }
    .footer-note a {
      color: var(--primary);
      text-decoration: none;
    }
    .footer-note a:hover {
      text-decoration: underline;
    }
    @media (max-width: 640px) {
      .wrapper {
        padding: 20px 14px;
      }
      .formula-stage {
        padding: 20px 10px;
      }
      h1 {
        font-size: 1.25rem;
      }
    }
  </style>
</head>
<body>
  <div class="wrapper">
    <div class="header-area">
      <div class="badge">${badgeText}</div>
      <h1>${headerTitle}</h1>
    </div>

    <div class="section-title">${formulaLabel}</div>
    <div class="formula-stage">
      ${displayContent}
    </div>

    <div class="source-header">
      <div class="section-title" style="margin-bottom:0;">${sourceLabel}</div>
      <button type="button" class="copy-btn" id="btn-copy">
        <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
          <rect x="9" y="9" width="13" height="13" rx="2" ry="2"></rect>
          <path d="M5 15H4a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h9a2 2 0 0 1 2 2v1"></path>
        </svg>
        <span id="btn-copy-text">${copyBtnLabel}</span>
      </button>
    </div>
    <div class="source-block">
      <pre><code id="source-display">${escapedCode}</code></pre>
    </div>

    <div class="footer-note">
      ${footerText} · <a href="https://visual-tex.ai.studio" target="_blank" rel="noopener noreferrer">Visual-TeX</a>
    </div>
  </div>

  <!-- 安全存储 JSON 格式公式数据，禁止直接拼装进未受控 script 标签 -->
  <script id="formula-data" type="application/json">${safeJsonData}</script>

  <script>
    (function() {
      var copyBtn = document.getElementById('btn-copy');
      var copyText = document.getElementById('btn-copy-text');
      var originalLabel = ${JSON.stringify(copyBtnLabel)};
      var copiedLabel = ${JSON.stringify(copiedToastLabel)};

      function getFormula() {
        var el = document.getElementById('formula-data');
        if (!el) return '';
        try {
          return JSON.parse(el.textContent || '""');
        } catch (e) {
          return '';
        }
      }

      function fallbackCopy(text) {
        var textarea = document.createElement('textarea');
        textarea.value = text;
        textarea.style.position = 'fixed';
        textarea.style.left = '-9999px';
        textarea.style.top = '0';
        document.body.appendChild(textarea);
        textarea.select();
        var ok = false;
        try {
          ok = document.execCommand('copy');
        } catch (err) {}
        document.body.removeChild(textarea);
        return ok;
      }

      if (copyBtn) {
        copyBtn.addEventListener('click', function(e) {
          e.preventDefault();
          var formula = getFormula();
          if (!formula) return;

          var success = function() {
            copyBtn.classList.add('copied');
            if (copyText) copyText.textContent = copiedLabel;
            setTimeout(function() {
              copyBtn.classList.remove('copied');
              if (copyText) copyText.textContent = originalLabel;
            }, 2000);
          };

          if (navigator.clipboard && window.isSecureContext) {
            navigator.clipboard.writeText(formula).then(success).catch(function() {
              if (fallbackCopy(formula)) success();
            });
          } else {
            if (fallbackCopy(formula)) success();
          }
        });
      }
    })();
  </script>
</body>
</html>`;
}
